WITH CTE_PRIMERLIQUIDACION AS (
 SELECT NSETTLEMENT_NUM
        ,HLIQ.DOPERDATE AS FECHA_TRANSACCION
        ,HLIQ.NUSERCODE AS COD_USUARIO 
        ,TRIM(CLI.SCLIENAME) USUARIO
 FROM CLAIM_SETT_HIS HLIQ
  INNER JOIN USERS USR ON HLIQ.NUSERCODE= USR.NUSERCODE
  INNER JOIN CLIENT CLI ON USR.SCLIENT = CLI.SCLIENT
 WHERE HLIQ.NMOVEMENT_TYPE=1
)
SELECT 
 VPOL.nbranch
, VPOL.nproduct
, Vpol.FrecuenciaPago
, VPOL.CodRegionalPoliza
, VPOL.RegionalPoliza
, TO_CHAR(VPOL.npolicy) AS NRO_POLIZA
, VPOL.INICIOVIGENCIAPOLIZA
, VPOL.FINVIGENCIAPOLIZA
, VPOL.CAPITALMO
, VPOL.CAPITALML
, VPOL.PRODUCTO
, UPPER(VPOL.CONTRATANTE) AS CONTRATANTE
, TRIM(CLI1.SCLIENAME) AS ASEGURADO_TITULAR
, TRIM(CLI2.SCLIENAME) AS ASEGURADO
, CL.NCLAIM AS NRO_SINIESTRO
, TRIM(T135.SDESCRIPT) AS ESTADO_SINIESTRO
, PCL.DREPDATE AS FECHA_DECUNCIA
, PCL.DOCCURDATE AS FECHA_OCURRENCIA
, TO_CHAR(PCL.DOCCURDATE,'YYYY') AS ANIO_OCURRENCIA
, ORD.DORDERDATE AS FECHA_ACEPTACION
, ORD.NORDER_NUM AS  NRO_ORDEN
, TRIM(T9241.SDESCRIPT) AS ESTADO_ORDEN
, ORD.NCURREN_DOC AS COD_MONEDA_ORDEN
, TRIM(T11.SDESCRIPT) AS MONEDA_ORDEN
, ODET.NAMOUNT_UNITAMV AS ARANCEL
, NVL(ODET.NAMOUNT_DEDUCOIN,0) AS COASEGURO 
, NVL(ODET.NAMOUNT_DEDUCTIBLE,0) AS DEDUCIBLE  -- VER
, VOU.NAMOUNT_DOCU AS MONTO_PRESENTADO
--, ODET.NAMOUNT_ORDEN AS MONTO_PRESENTADO
, ODET.NAMOUNT_TOTAL AS MONTO_SINIESTRADO
, 0 AS DESCUENTO_IVA
, 0 AS RETENCION_IVA
, 0 AS DCTO_CONVENIO
, ODET.NAMOUNT_PAY AS MONTO_A_PAGAR_COMPANIA
, ORD.NEXCHANGE AS TC
, (ODET.NAMOUNT_PAY  * 0.13) AS CREDITO_FISCAL
, (ODET.NAMOUNT_PAY  * 0.87) AS AL_87PORC
, 0 AS AL_100PORC
, (0 +  (ODET.NAMOUNT_PAY  * 0.87) + 0) AS TOTAL_NETO
, (ODET.NAMOUNT_PAY  * 0.13) + (ODET.NAMOUNT_PAY  * 0.87) AS TOTAL

, LQ.DSETTLEMENTDAT AS FECHA_LIQUIDACION
, LQ.NSETTLEMENT_NUM AS NRO_LIQUIDACION
, VOU.NVOUCHER_NUM AS NRO_FACTURA
, VOU.DISSUEDAT AS FECHA_EMISION

, TPRO.NPROVIDER AS COD_PROVEEDOR
, TRIM(PCLI.SCLIENAME) AS PROVEEDOR 
, LQ.NOFFICE
, TRIM(REG.SDESCRIPT) REGIONAL_LIQUIDACION
, TRIM(T9250.SDESCRIPT) AS ESTADO_LIQUIDACION
, VPOL.TIPOINTERMEDIARIO
, VPOL.INTERMEDIARIO
, TRIM(T8604.SDESCRIPT) AS TIPO_ATENCION
, MBEF.SBENEFIT AS COD_PRESTACION
, TRIM(MBEF.SDESCRIPT) AS PRESTACION
, TAI.SILLNESS AS COD_PATOLOGIA
, TRIM(TAI.SDESCRIPT) AS PATOLOGIA
, TRIM(T9212.SDESCRIPT) AS LIQUIDACIONA

, LQ.DSETTLEMENTDAT AS FECHA_LIQUIDACION
, TRIM(T9252.SDESCRIPT) AS TIPO_PAGO
, LQ.DPAYAUTH AS FECHA_AUTORIZACION_PAGO

,ODET.SREJECTOBSV DIAGNOSTICO
,TRIM(T7027.SDESCRIPT) AS TIPO_PROVEEDOR
,CASE TPRO.NTYPEPROV
          WHEN 1 THEN TRIM(TPS.SDESCRIPT)
          ELSE TRIM(T8603.SDESCRIPT)     
  END AS ESPECIALIDAD_CATEGORIA
,PLIQ.COD_USUARIO
,PLIQ.USUARIO
  
  
FROM CLAIM_SETTLEMENT LQ
INNER JOIN CLAIM_SETT_ORDER SORD ON LQ.NSETTLEMENT_NUM = SORD.NSETTLEMENT_NUM
INNER JOIN CLAIM_ORDER ORD ON SORD.NORDER_NUM = ORD.NORDER_NUM
INNER JOIN CLORDER_DETAIL ODET ON ORD.NCLAIM = ODET.NCLAIM
INNER JOIN CLAIM CL ON ORD.NCLAIM = CL.NCLAIM
INNER JOIN PRECLAIM PCL ON CL.NIDPRECLAIM = PCL.NIDPRECLAIM
INNER JOIN CLIENT CLI1 ON CL.SCLIENT=CLI1.SCLIENT --
INNER JOIN CLIENT CLI2 ON CL.SCLIENT2=CLI2.SCLIENT
INNER JOIN NS_View_DatosGeneralesPoliza VPOL ON CL.NBRANCH= VPOL.NBRANCH              
                                                 AND CL.NPRODUCT= VPOL.NPRODUCT
                                                 AND CL.NPolicy= VPOL.NPolicy
INNER JOIN TABLE8604 T8604 ON ORD.STYPECARE = T8604.STYPECARE
INNER JOIN TABLE9212 T9212 ON ORD.NCLAIMANTTYPE = T9212.NCLAIMANTTYPE
INNER JOIN TABLE11 T11 ON ORD.NCURREN_DOC = T11.NCODIGINT
INNER JOIN TABLE135 T135 ON CL.SSTACLAIM= T135.SSTACLAIM
INNER JOIN TABLE9241 T9241 ON ORD.NSTATUS_ORDER = T9241.NSTATUS_ORDER
INNER JOIN TABLE9250 T9250 ON LQ.NSETTLEMENT_STAT = T9250.NSETTLEMENT_STAT
INNER JOIN TABLE9252 T9252 ON LQ.NPAYMENT_METHOD = T9252.NPAYMENT_METHOD


INNER JOIN TAB_PROVIDER TPRO ON ORD.NPROVIDER= TPRO.NPROVIDER
INNER JOIN CLIENT PCLI ON TPRO.SCLIENT= PCLI.SCLIENT
LEFT JOIN TABLE7027 T7027 ON TPRO.NTYPEPROV = T7027.NTYPEPROV
LEFT JOIN TAB_PROV_MEDSPEC TPM ON TPRO.NPROVIDER = TPM.NPROVIDER AND TPM.NMAIN_MEDSPECIALIALTY=1
LEFT JOIN TABLE8603 T8603 ON TPM.SMEDSPECIALIALTY = T8603.SMEDSPECIALIALTY
LEFT JOIN TAB_PROV_SUBTYPES TPS ON TPRO.NTYPEPROV = TPS.NTYPEPROV AND TPRO.NSUBTYPEPROV = TPS.NSUBTYPEPROV

INNER JOIN MEDICALBENEFITS MBEF ON ODET.SBENEFIT = MBEF.SBENEFIT
--LEFT JOIN TAB_MEDICALFEES TMED ON LQ.NPROVIDER = TMED.NPROVIDER
--LEFT JOIN MEDICALFEES MED ON ORD.NIDMEDICALFEE= MED.NIDMEDICALFEE AND  MBEF.SBENEFIT = MED.SBENEFITCODE

INNER JOIN TAB_AM_ILL TAI ON ODET.SILLNESS = TAI.SILLNESS
INNER JOIN CLAIM_SETT_VOUCHER  SVOU ON LQ.NSETTLEMENT_NUM = SVOU.NSETTLEMENT_NUM
INNER JOIN CLAIM_VOUCHER VOU ON SVOU.NCLAIM_VOUCHER = VOU.NCLAIM_VOUCHER
INNER JOIN TABLE9 REG On LQ.noffice = REG.noffice
INNER JOIN CTE_PRIMERLIQUIDACION PLIQ ON LQ.NSETTLEMENT_NUM=  PLIQ.NSETTLEMENT_NUM
WHERE CL.NCLAIM = '260500103' ---'260500136'
ORDER BY LQ.DSETTLEMENTDAT