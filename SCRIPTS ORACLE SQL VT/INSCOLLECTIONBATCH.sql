               BUL.NCURRENCY  , BUL.NEXCHANGE , BUL.ROWID       ,
               BUL.NWAY_PAY
          FROM BULLETINS BUL
         WHERE NBULLETINS = INSREJECTIMPUTATION.NBULLETINS;

