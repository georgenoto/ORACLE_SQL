                              SSTATISI      => '2'             ,
                              NUSERCODE     => NUSERCODE       ,
                              DLEDGERDAT    => TRUNC(SYSDATE)  ,
                              NTYPE         => 40              , -- 40) salida de cobranza (TABLE 6)
