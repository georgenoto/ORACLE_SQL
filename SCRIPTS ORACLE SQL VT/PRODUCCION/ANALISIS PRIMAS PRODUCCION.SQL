---DETAIL_PRE : Detalle o desglose del recibo (Un registro por cada cobertura, recargo, descuento e impuesto facturado en el recibo.)
---La suma de los importes registrados en este archivo corresponden a la prima total del recibo.
select * from DETAIL_PRE where nreceipt=3894 ORDER BY STYPE_DETAI,NDET_CODE

--- STYPE_DETAI=1  NDET_CODE(5,45,50,60,65,70,85,95,100,110)
--- STYPE_DETAI=2  NDET_CODE(10:GastosAdm ,11:Utilidad,12:Marketing,13:Cobranza,20:Costos intermediacion)
--- STYPE_DETAI=3  NDET_CODE(APS:30,FPA:31,IT:32,IVA:33)
--- STYPE_DETAI=5  NDET_CODE(6: RECARGO COMERCIAL)
----------------------------------------------------------------------------------------------------------------------------------------
---DISCO_EXPR : Recargos/Descuentos/Impuestos de un producto
SELECT NDISEXPRC,SDESCRIPT,SSHORT_DES, DEFFECDATE  
FROM DISCO_EXPR where NBRANCH=5 and NPRODUCT=1 AND DNULLDATE IS NULL
ORDER BY NDISEXPRC
---DISCO_EXPR.NDISEXPRC = DETAIL_PRE.NDET_CODE
----------------------------------------------------------------------------------------------------------------------------------------



--IT 
SELECT SUM(DPRE.NPREMIUM) AS IT FROM DETAIL_PRE DPRE 
LEFT JOIN DISCO_EXPR DEXP ON DPRE.NBRANCH = DEXP.NBRANCH AND DPRE.NPRODUCT = DEXP.NPRODUCT                  
                   AND DPRE.NDET_CODE = DEXP.NDISEXPRC AND DNULLDATE IS NULL
WHERE DPRE.NRECEIPT=3894
AND DEXP.NDISEXPRC = 32 --IT 
--IVA 
SELECT SUM(DPRE.NPREMIUM) AS IVA FROM DETAIL_PRE DPRE 
LEFT JOIN DISCO_EXPR DEXP ON DPRE.NBRANCH = DEXP.NBRANCH AND DPRE.NPRODUCT = DEXP.NPRODUCT                  
                   AND DPRE.NDET_CODE = DEXP.NDISEXPRC AND DNULLDATE IS NULL
WHERE DPRE.NRECEIPT=3894
AND DEXP.NDISEXPRC = 33  
--APS 
SELECT SUM(DPRE.NPREMIUM) AS aps FROM DETAIL_PRE DPRE 
LEFT JOIN DISCO_EXPR DEXP ON DPRE.NBRANCH = DEXP.NBRANCH AND DPRE.NPRODUCT = DEXP.NPRODUCT                  
                   AND DPRE.NDET_CODE = DEXP.NDISEXPRC AND DNULLDATE IS NULL
WHERE DPRE.NRECEIPT=3894
AND DEXP.NDISEXPRC = 30  
-- RECARGOS ADICIONALES
SELECT SUM(DPRE.NPREMIUM) AS aps FROM DETAIL_PRE DPRE 
LEFT JOIN DISCO_EXPR DEXP ON DPRE.NBRANCH = DEXP.NBRANCH AND DPRE.NPRODUCT = DEXP.NPRODUCT                  
                   AND DPRE.NDET_CODE = DEXP.NDISEXPRC AND DNULLDATE IS NULL
WHERE DPRE.NRECEIPT=3894
AND DEXP.NDISEXPRC = 31 
--PRIMA ADICIONAL
SELECT SUM(NVL(DPRE.NPREMIUM,0)) 
FROM DETAIL_PRE DPRE 
LEFT JOIN DISCO_EXPR DEXP ON DPRE.NBRANCH = DEXP.NBRANCH AND DPRE.NPRODUCT = DEXP.NPRODUCT                  
                   AND DPRE.NDET_CODE = DEXP.NDISEXPRC AND DNULLDATE IS NULL
WHERE DPRE.NRECEIPT=3894
AND DPRE.STYPE_DETAI  =3 AND DPRE.NDET_CODE <> 33
--PRIMA NETA
SELECT SUM(NVL(DPRE.NPREMIUM,0)) 
FROM DETAIL_PRE DPRE 
LEFT JOIN DISCO_EXPR DEXP ON DPRE.NBRANCH = DEXP.NBRANCH AND DPRE.NPRODUCT = DEXP.NPRODUCT                  
                   AND DPRE.NDET_CODE = DEXP.NDISEXPRC AND DNULLDATE IS NULL
WHERE DPRE.NRECEIPT=3894
AND DPRE.STYPE_DETAI not in (3,8,4)

--PRIMA TOTAL
SELECT SUM(NVL(DPRE.NPREMIUM,0)  +  NVL(DPRE.NTAXAMOUNT,0)) 
FROM DETAIL_PRE DPRE 
LEFT JOIN DISCO_EXPR DEXP ON DPRE.NBRANCH = DEXP.NBRANCH AND DPRE.NPRODUCT = DEXP.NPRODUCT                  
                   AND DPRE.NDET_CODE = DEXP.NDISEXPRC AND DNULLDATE IS NULL
WHERE DPRE.NRECEIPT=3894
AND DPRE.STYPE_DETAI not in (3,4)
-- COMISSION
-- COMISSION
SELECT MAX(DPRE.NCOMMI_RATE) PORCENTAJE,SUM(NVL(DPRE.NCOMMISION,0) ) MONTO_COMISION
, MAX(DPRE.NCOMSUP_RATE) PORCENTAJE_SUPERVISOR, SUM(DPRE.NCOM_SUPER) MONTO_SUPERVISOR
FROM DETAIL_PRE DPRE 
LEFT JOIN DISCO_EXPR DEXP ON DPRE.NBRANCH = DEXP.NBRANCH AND DPRE.NPRODUCT = DEXP.NPRODUCT                  
                   AND DPRE.NDET_CODE = DEXP.NDISEXPRC AND DNULLDATE IS NULL
WHERE DPRE.NRECEIPT=3894

