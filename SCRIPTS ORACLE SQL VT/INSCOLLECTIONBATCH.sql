      EXCEPTION
        WHEN OTHERS THEN
        NNUMDIGIT_AUX  := 10;
      END;
   RETURN  LPAD(TO_CHAR(TRIM(SDOCUMENT)),NNUMDIGIT_AUX ,'0')    ;

END;



