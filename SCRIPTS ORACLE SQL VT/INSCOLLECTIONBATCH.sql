        END IF;

/*+ REGISTRAR MOVIMIENTO DE RECHAZO SIEMPRE QUE EXISTA RECIBO */
        IF BDATA_FOUND THEN
        
            IF NSTATUS_PRE NOT IN (2,5,9) THEN
                INSPREMIUM_MO(NRECEIPT      => C_BDT.NRECEIPT  ,
                              NPRODUCT      => NPRODUCT_AUX    ,
                              NBRANCH       => NBRANCH_AUX     ,
