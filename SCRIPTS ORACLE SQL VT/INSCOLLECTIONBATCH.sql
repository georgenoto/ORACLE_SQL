                              NCAUSE_AMEN   => NULL            ,
                              SCESSICOI     => '2'             ,
                              SCHANG_ACC    => NULL            ,
                              NCURRENCY     => NCURRENCY_AUX   ,
                              SDOCNUMBE     => NULL            ,
                              SIND_REVER    => '2'             ,
                              NINT_MORA     => 0               ,
                              SINTERMEI     => NULL            ,
                              NNULLCODE     => NULL            ,
                              SPAY_FORM     => SPAY_FORM_AUX   ,
                              DPOSTED       => NULL            ,
                              NPREMIUM      => NPREMIUM_AUX    ,
