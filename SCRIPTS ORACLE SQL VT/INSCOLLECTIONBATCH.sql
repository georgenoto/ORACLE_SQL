    EXCEPTION
        WHEN OTHERS THEN
            NULL;
    END;

/*+ SE CREA EL REGISTRO DE RECHAZO PARA EL REPORTE POR DOCUMENTO DEL BOLETIN */
    FOR C_BDT IN C_BULLETINS_DET(NBULLETINS) LOOP

/*+SE INICIALIZA ERROR DE DETALLE CON LO ENCONTRADO EN CABECERA*/
        NCURRENCY_AUX   := 0;

